  async function drag(page, from, to) {
    await from.scrollIntoViewIfNeeded()
    // Đưa cột đích vào khung nhìn (cuộn ít nhất) như người dùng thật; thả ra ngoài màn hình phụ thuộc tốc độ tự cuộn của bảng
    await to.evaluate((el) => el.scrollIntoView({ block: 'nearest', inline: 'nearest' }))
    const a = await from.boundingBox()
    const b = await to.boundingBox()
    const [x0, y0] = [a.x + a.width / 2, a.y + a.height / 2]
    const [x1, y1] = [b.x + b.width / 2, Math.min(Math.max(y0, b.y + 40), b.y + b.height - 10)]
    await page.mouse.move(x0, y0)
    await page.mouse.down()
    for (let i = 1; i <= 12; i++) await page.mouse.move(x0 + ((x1 - x0) * i) / 12, y0 + ((y1 - y0) * i) / 12)
    if (process.env.DEBUG_DRAG) await page.screenshot({ path: `${OUT}debug-drag.png` })
    await page.mouse.up()
  }

