async function newPage(viewport = { width: 1440, height: 900 }) {
  const ctx = await browser.newContext({ viewport, locale: 'vi-VN', timezoneId: 'Asia/Ho_Chi_Minh' })
  const page = await ctx.newPage()
  page.on('pageerror', (e) => problems.push(`pageerror: ${e.message}`))
  page.on('console', (m) => m.type() === 'error' && !m.text().includes('Failed to load resource') && problems.push(`console: ${m.text()}`))
  page.on('response', (r) => r.status() >= 500 && r.status() !== 501 && problems.push(`HTTP ${r.status()} ${r.url()}`))
  return page
}

